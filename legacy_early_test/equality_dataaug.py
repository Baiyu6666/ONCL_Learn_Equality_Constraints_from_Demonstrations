def make_model_from_cfg(cfg: Dict) -> Tuple[str, Callable[[], nn.Module], int, float]:
    """Return (name, constructor, epochs, lr) for a single row."""
    t = cfg["type"].lower()
    name = cfg.get("name")
    if t == "nn":
        hidden = int(cfg.get("hidden", 16))
        layers = int(cfg.get("layers", 2))
        epochs = int(cfg.get("epochs", EPOCHS_NN))
        lr = float(cfg.get("lr", LR_NN))
        def ctor():
            return MLPImplicit(hidden=hidden, layers=layers)
        if name is None:
            name = f"NN({hidden}x{hidden})x{layers}"
        return name, ctor, epochs, lr
    elif t == "poly":
        degree = int(cfg.get("degree", 2))
        epochs = int(cfg.get("epochs", EPOCHS_POLY))
        lr = float(cfg.get("lr", LR_POLY))
        def ctor():
            return PolyImplicit(degree=degree)
        if name is None:
            name = f"Poly(deg={degree})"
        return name, ctor, epochs, lr
    else:
        raise ValueError(f"Unknown model type in ARCH_CONFIGS: {t}")

